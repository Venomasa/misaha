function t(key, fallback = '') {
    const lang = AppSettings.lang || 'ar';
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
    return dict[key] || fallback || key;
}

function getCornerName(idx) {
    const lettersAr = ['أ', 'ب', 'ج', 'د', 'هـ', 'و', 'ز', 'ح', 'ط', 'ي', 'ك', 'ل'];
    const lettersEn = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L'];
    const isEn = (AppSettings.lang === 'en');
    return isEn ? (lettersEn[idx] || `P${idx + 1}`) : (lettersAr[idx] || `ن${idx + 1}`);
}

function getEdgeName(i, j) {
    const isEn = (AppSettings.lang === 'en');
    const pA = getCornerName(i);
    const pB = getCornerName(j);
    return isEn ? `Side ${pA}-${pB}` : `الضلع ${pA}-${pB}`;
}

function getChordName(i, j) {
    const isEn = (AppSettings.lang === 'en');
    const pA = getCornerName(i);
    const pB = getCornerName(j);
    return isEn ? `Chord ${pA}-${pB}` : `الوتر ${pA}-${pB}`;
}

function changeAppLanguage(lang) {
    AppSettings.lang = (lang === 'en' ? 'en' : 'ar');
    document.documentElement.lang = AppSettings.lang;
    document.documentElement.dir = (AppSettings.lang === 'en' ? 'ltr' : 'rtl');

    const dict = TRANSLATIONS[AppSettings.lang];
    if (dict) {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (dict[key]) {
                el.textContent = dict[key];
            }
        });
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            if (dict[key]) {
                el.setAttribute('title', dict[key]);
            }
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (dict[key]) {
                el.setAttribute('placeholder', dict[key]);
            }
        });
    }

    const selLang = document.getElementById('setLanguage');
    if (selLang) selLang.value = AppSettings.lang;

    try {
        localStorage.setItem('misaha_lang', AppSettings.lang);
    } catch (_) {}

    // Refresh dynamic components if defined
    if (typeof renderPlayground === 'function') renderPlayground();
    if (typeof updateCalculationsAndUI === 'function') updateCalculationsAndUI();
    if (typeof renderFixedShapeDiagram === 'function') renderFixedShapeDiagram();
    if (typeof updateFixedDiagramLive === 'function') updateFixedDiagramLive();
    if (typeof updateExportOptionsLive === 'function') updateExportOptionsLive();
}
